export const shellMessages: Record<AppLocale, ShellCopy> = { vi, en };

const navKeys = {
  Home: 'home',
  Schedule: 'schedule',
  Register: 'register',
  Grades: 'grades',
  Alerts: 'alerts',
  Gradebook: 'gradebook',
  Students: 'students',
  Lecturers: 'lecturers',
} as const;

/** Registry tab label (English identifier) → label in the given locale. */
export function localizedNavLabel(locale: AppLocale, label: string): string {
  const key = navKeys[label as keyof typeof navKeys];
  return key ? shellMessages[locale].nav[key] : label;
}

export function fillShellCopy(template: string, params: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(params[key] ?? ''));
}
